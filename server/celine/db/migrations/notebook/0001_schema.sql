-- The whole schema of var/notebook/.index.db, attached to celine.db as `notebook`
-- (core/store.py): the index of her notes (skills/notebook_index.py), beside the note
-- files and rebuilt from them at startup (skills/notebook.py reconcile). A fresh file
-- applies it and is at 1.

CREATE TABLE notebook_index (
  path       TEXT PRIMARY KEY,
  summary    TEXT NOT NULL,     -- hers. never generated by us
  bytes      INTEGER NOT NULL,
  touched_at TEXT NOT NULL,
  created_at TEXT NOT NULL
);
CREATE INDEX notebook_touched ON notebook_index(touched_at DESC);

CREATE VIRTUAL TABLE notebook_fts USING fts5(path, summary, body,
                                             tokenize='porter unicode61');
